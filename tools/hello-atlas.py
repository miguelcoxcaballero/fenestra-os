"""hello-atlas.py SRC OUT [--cell 128]

Packs a Windows Hello style face animation into one texture atlas for the lock screen
(shells/org.fenestra.desktop/contents/lockscreen/Hello.qml): OUT/atlas.png + OUT/frames.qml.

SRC is either
  * a directory with searching.gif and authentication.gif (white artwork on black: the luminance
    is the alpha), e.g. the user's own copy of Windows' animation (never shipped with Fenestra), or
  * a directory with frames.json + PNGs (Fenestra's open drawing, assets/generated/hello).

Every distinct frame is stored once; sequences are lists of [cell, ms]. The static pre-roll of
"authentication" (the frames before the first change) is dropped: the scan already shows it,
and its final hold is cut to 200 ms (the screen unlocks after the smile).
"""
import hashlib
import json
import math
import os
import sys

from PIL import Image


def gif_frames(path):
    im = Image.open(path)
    out = []
    for i in range(im.n_frames):
        im.seek(i)
        rgb = im.convert('RGB')
        rgba = Image.new('RGBA', rgb.size, (255, 255, 255, 0))
        rgba.putalpha(rgb.getchannel('R'))
        out.append((rgba, im.info.get('duration', 30) or 30))
    return out


def png_frames(src, seq):
    return [(Image.open(os.path.join(src, f['file'])).convert('LA').convert('RGBA'), f['duration']) for f in seq]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    cell = int(sys.argv[sys.argv.index('--cell') + 1]) if '--cell' in sys.argv else 128
    if '--cell' in sys.argv:
        args.remove(str(cell))
    src, out = args
    os.makedirs(out, exist_ok=True)
    if os.path.exists(os.path.join(src, 'searching.gif')):
        seqs = {n: gif_frames(os.path.join(src, n + '.gif')) for n in ('searching', 'authentication')}
    else:
        manifest = json.load(open(os.path.join(src, 'frames.json')))
        seqs = {n: png_frames(src, manifest[n]) for n in ('searching', 'authentication')}
    # Fenestra's PNG frames are grey + alpha: white artwork, the grey only antialiasing.
    for n, frames in seqs.items():
        seqs[n] = [(Image.merge('RGBA', (*[Image.new('L', im.size, 255)] * 3, im.getchannel('A'))), d) for im, d in frames]
    auth = seqs['authentication']
    keys = [hashlib.sha1(im.tobytes()).digest() for im, _ in auth]
    first = next((i for i in range(1, len(keys)) if keys[i] != keys[0]), 0)
    seqs['authentication'] = auth[max(0, first - 1):]
    cells, index, manifest = [], {}, {}
    for n, frames in seqs.items():
        seq = []
        for im, d in frames:
            k = hashlib.sha1(im.tobytes()).digest()
            if k not in index:
                index[k] = len(cells)
                cells.append(im.resize((cell, cell), Image.LANCZOS))
            if seq and seq[-1][0] == index[k]:
                seq[-1][1] += d          # merge repeats: fewer entries to search, same timing
            else:
                seq.append([index[k], d])
        manifest[n] = seq
    # The success smile holds its last frame for a second in the source; the lock screen unlocks
    # once it is drawn, so keep 200 ms of it.
    manifest['authentication'][-1][1] = min(manifest['authentication'][-1][1], 200)
    cols = math.ceil(math.sqrt(len(cells)))
    rows = math.ceil(len(cells) / cols)
    atlas = Image.new('RGBA', (cols * cell, rows * cell), (255, 255, 255, 0))
    for i, im in enumerate(cells):
        atlas.paste(im, ((i % cols) * cell, (i // cols) * cell))
    atlas.save(os.path.join(out, 'atlas.png'), optimize=True)
    with open(os.path.join(out, 'frames.qml'), 'w') as f:
        f.write('// Generated by tools/hello-atlas.py: cells of atlas.png and [cell, ms] sequences.\n')
        f.write('import QtQuick\nQtObject {\n')
        f.write('    readonly property string atlas: "atlas.png"\n')
        f.write(f'    readonly property int cellSize: {cell}\n    readonly property int cols: {cols}\n')
        for n, seq in manifest.items():
            f.write(f'    readonly property var {n}: {json.dumps(seq, separators=(",", ":"))}\n')
        f.write('}\n')
    total = {n: sum(d for _, d in s) for n, s in manifest.items()}
    print(f'{len(cells)} frames in a {cols}x{rows} atlas of {cell} px; sequences (ms): {total}')


if __name__ == '__main__':
    main()
