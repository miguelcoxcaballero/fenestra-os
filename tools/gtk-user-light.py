#!/usr/bin/env python3
"""Append light-mode (and live-accent) counterparts of the user GTK 4 CSS rules.

    tools/gtk-user-light.py desktop/skel/.config/gtk-4.0/gtk.css [~/.config/gtk-4.0/gtk.css ...]

The hand-written user CSS (caption buttons, menus, File Explorer) is authored in
Windows 11 dark colours. This regenerates, at the end of each file, between
the markers below:
  @media (prefers-color-scheme: light) { ...every rule with a colour, in the
      Windows 11 light palette... }
  @media (prefers-color-scheme: dark)  { ...rules using the hard-coded accent,
      re-pointed at @fenestra_accent_dark... }
GTK >= 4.20 evaluates prefers-color-scheme live (also in libadwaita apps such
as Nautilus), so Explorer switches with Settings > Personalization > Colors.
Re-run after editing the dark rules; the generated block is replaced.
"""
import re, sys

BEGIN = '/* ---- Fenestra light mode + accent (generated by tools/gtk-user-light.py; do not edit) ---- */'
END = '/* ---- end Fenestra light mode ---- */'

# Windows 11 dark -> light (File Explorer / menus / captions).
LIGHT = {
    '#191919': '#ffffff', '#202020': '#f9f9f9', '#252525': '#f9f9f9', '#292929': '#f9f9f9',
    '#2b2b2b': '#ffffff', '#282828': '#f0f0f0', '#2d2d2d': '#f0f0f0', '#303030': '#f0f0f0',
    '#323232': '#ebebeb', '#333333': '#e5e5e5', '#353535': '#e5e5e5', '#383838': '#e5e5e5',
    '#3a3a3a': '#e5e5e5', '#454545': '#d1d1d1',
    '#f4f4f4': '#1a1a1a', '#ffffff': '#1a1a1a', 'white': '#1a1a1a', '#eeeeee': '#1a1a1a',
    '#c5c5c5': '#5f5f5f', '#bfbfbf': '#5f5f5f', '#d0d0d0': '#5f5f5f', '#d4d4d4': '#5f5f5f',
    'rgba(44,44,44,0.96)': 'rgba(249,249,249,0.96)',
}
ACCENT = {'#4cc2ff', '#48b1e8'}
# Explorer chrome glyphs (win11-explorer-* icons) are drawn white for the dark
# chrome; light mode inverts the monochrome ones instead of shipping a second set.
EXTRA_LIGHT = [
    '.win11-explorer .win11-commandbar image, .win11-explorer .win11-navigation image, '
    '.win11-explorer image.fenestra-pin, .win11-explorer .win11-cmd-chevron { -gtk-icon-filter: invert(0.9); }',
]
# Rules painted on a fixed colour (red close button) keep their colours.
KEEP = re.compile(r'#c42b1c|#a51c28|#b3261e', re.I)
TOKEN = re.compile(r'#[0-9a-fA-F]{3,6}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b')


def rules(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    for m in re.finditer(r'([^{}@;]+)\{([^{}]*)\}', css):
        yield m.group(1).strip(), m.group(2)


def decls(body):
    return [d.strip() for d in body.split(';') if d.strip() and ':' in d]


def light_value(prop, value, accent_rule):
    def sub(m):
        t = m.group(0)
        k = t.lower().replace(' ', '')
        if k in ACCENT:
            return '@fenestra_accent_light' if k == '#4cc2ff' else 'shade(@fenestra_accent_light, 1.1)'
        if k == '#000000' and accent_rule:
            return '@fenestra_accent_light_fg'
        if k in LIGHT:
            # dark greys used as lines become Windows' light divider colour
            if 'border' in prop and LIGHT[k].startswith('#f') or LIGHT[k] == '#ffffff' and 'border' in prop:
                return '#e5e5e5'
            return LIGHT[k]
        r = re.fullmatch(r'rgba\(255,255,255,([\d.]+)\)', k)
        if r:  # white veil on dark -> black veil on light
            return f'rgba(0,0,0,{min(0.12, round(float(r.group(1)) * 0.6, 3))})'
        return t
    return TOKEN.sub(sub, value)


def dark_value(value):
    return TOKEN.sub(lambda m: {'#4cc2ff': '@fenestra_accent_dark', '#48b1e8': 'shade(@fenestra_accent_dark, 0.92)',
                                '#000000': '@fenestra_accent_dark_fg'}.get(m.group(0).lower(), m.group(0)), value)


def generate(css):
    light, dark = [], []
    for sel, body in rules(css):
        if KEEP.search(body):
            continue
        accent_rule = any(a in body.lower() for a in ACCENT)
        ld, dd = [], []
        for d in decls(body):
            prop, value = (x.strip() for x in d.split(':', 1))
            if not TOKEN.search(value):
                continue
            lv = light_value(prop, value, accent_rule)
            if lv != value:
                ld.append(f'{prop}: {lv};')
            if accent_rule:
                dv = dark_value(value)
                if dv != value:
                    dd.append(f'{prop}: {dv};')
        if ld:
            light.append(f'  {sel} {{ {" ".join(ld)} }}')
        if dd:
            dark.append(f'  {sel} {{ {" ".join(dd)} }}')
    out = [BEGIN]
    if dark:
        out += ['@media (prefers-color-scheme: dark) {', *dark, '}']
    out += ['@media (prefers-color-scheme: light) {', *light, *('  ' + e for e in EXTRA_LIGHT), '}', END]
    return '\n'.join(out) + '\n'


def main():
    for path in sys.argv[1:]:
        text = open(path).read()
        if BEGIN in text:
            head, rest = text.split(BEGIN, 1)
            tail = rest.split(END, 1)[1] if END in rest else ''
        else:
            head, tail = text, ''
        base = head.rstrip('\n') + '\n' + tail.strip('\n')
        base = base.rstrip('\n') + '\n\n'
        open(path, 'w').write(base + generate(base))
        print('updated', path)


if __name__ == '__main__':
    main()
