#!/usr/bin/python3
"""Generates src/ReferenceIcons.g.cs from design/reference/icons.json (branch visual/reference).

Usage: gen-reference-icons.py PATH/TO/icons.json [--out src/ReferenceIcons.g.cs]

icons.json holds names, module ids, Segoe Fluent Icons code points and where each icon appears in
the reference screenshots; no artwork. The generated table carries the same (names, ids, code
points), so the extractor never reads icons.json at run time and never embeds any outline or image.
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent


def cs(s):
    if s is None:
        return 'null'
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def split_package(pkg):
    """'Family_publisher (App hint)' -> (family, hint). Families are [A-Za-z0-9.-]+_[a-z0-9]{13}."""
    if not pkg:
        return None, None
    m = re.match(r'^([A-Za-z0-9.\-]+_[a-z0-9]{13})\s*(?:\((.*)\))?\s*$', pkg.strip())
    if m:
        return m.group(1), (m.group(2) or '').strip() or None
    if re.match(r'^[A-Za-z0-9.\-]+$', pkg.strip()):
        return pkg.strip(), None      # a SystemApps folder name without publisher id (ImmersiveControlPanel)
    return None, None                 # '? (...)': unknown


def split_paths(path):
    """'A.exe (o C:\\Dir)' -> ['A.exe', 'C:\\Dir\\A.exe']; a single path -> [path]."""
    if not path:
        return []
    m = re.match(r'^(.*?)\s*\((?:o|or)\s+(.*)\)\s*$', path.strip())
    if not m:
        return [path.strip()]
    first, alt = m.group(1).strip(), m.group(2).strip()
    base = re.split(r'[\\/]', first)[-1]
    if not alt.lower().endswith(('.exe', '.dll', '.mun', '.png', '.svg')):
        alt = alt.rstrip('\\') + '\\' + base
    return [first, alt]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('icons_json')
    ap.add_argument('--out', default=str(HERE.parent / 'src' / 'ReferenceIcons.g.cs'))
    a = ap.parse_args()
    src = Path(a.icons_json)
    d = json.loads(src.read_text(encoding='utf-8'))
    try:
        rev = subprocess.run(['git', '-C', str(src.parent), 'log', '-1', '--format=%h', '--', src.name],
                             capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        rev = ''
    out = ['// <auto-generated/>',
           '// Generated by tools/gen-reference-icons.py from design/reference/icons.json'
           + (f' (visual/reference {rev})' if rev else '') + '. Do not edit by hand.',
           '// Names, module ids and code points only: no icon artwork is in this file.',
           'namespace FenestraIconExtractor;', '',
           'static partial class ReferenceIcons', '{',
           f'    public const string SourceRevision = {cs(rev)};', '']
    out.append('    public static readonly RefGlyph[] Glyphs =')
    out.append('    {')
    for g in d['glyphs']:
        cp = g.get('codepoint')
        cpv = f'0x{int(cp[2:], 16):04X}' if cp else 'null'
        out.append(f'        new({cs(g["name"])}, {cs(g.get("glyph"))}, {cpv}, {str(bool(g.get("verificado"))).lower()}),')
    out.append('    };')
    out.append('')
    out.append('    public static readonly RefApp[] Apps =')
    out.append('    {')
    for p in d['apps']:
        fam, hint = split_package(p.get('package'))
        paths = split_paths(p.get('path'))
        arr = 'new string[] { ' + ', '.join(cs(x) for x in paths) + ' }' if paths else 'System.Array.Empty<string>()'
        out.append(f'        new({cs(p["name"])}, {cs(p.get("module"))}, {cs(fam)}, {cs(hint)}, {arr}, '
                   f'{str(bool(p.get("verificado"))).lower()}),')
    out.append('    };')
    out.append('')
    out.append('    public static readonly RefModule[] Modules =')
    out.append('    {')
    for m in d['modules']:
        mid = m.get('id')
        out.append(f'        new({cs(m["name"])}, {cs(m.get("context"))}, {cs(m.get("module"))}, '
                   f'{mid if isinstance(mid, int) else "null"}, {cs(m.get("path"))}, {str(bool(m.get("verificado"))).lower()}),')
    out.append('    };')
    out.append('')
    out.append('    public static readonly RefBitmap[] Bitmaps =')
    out.append('    {')
    for b in d['bitmaps']:
        out.append(f'        new({cs(b["name"])}, {cs(b.get("origin"))}, {str(bool(b.get("verificado"))).lower()}),')
    out.append('    };')
    out.append('}')
    Path(a.out).write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{a.out}: {len(d["glyphs"])} glyphs, {len(d["apps"])} apps, {len(d["modules"])} modules, '
          f'{len(d["bitmaps"])} bitmaps')


if __name__ == '__main__':
    main()
