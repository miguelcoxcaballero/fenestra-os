# Exact shades of the default accent (the rest are derived).
_KNOWN = {"#0078D4": {"dark1": "#005FB8", "light2": "#60CDFF"}}

CONFIG = os.path.join(GLib.get_user_config_dir(), "fenestra", "accent.json")
SHELL_CSS = os.path.join(GLib.get_user_config_dir(), "fenestra", "accent-shell.css")


def _rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _hex(r, g, b):
    return "#%02X%02X%02X" % (round(r), round(g), round(b))


def _hls_shift(h, fn):
    r, g, b = (c / 255 for c in _rgb(h))
    hh, ll, ss = colorsys.rgb_to_hls(r, g, b)
    r, g, b = colorsys.hls_to_rgb(hh, max(0.0, min(1.0, fn(ll))), ss)
    return _hex(r * 255, g * 255, b * 255)


def dark1(h):
    """Shade used for fills on light surfaces."""
    h = h.upper()
    return _KNOWN.get(h, {}).get("dark1") or _hls_shift(h, lambda l: l * 0.85)


def light2(h):
    """Shade used for fills on dark surfaces (text on it is black)."""
    h = h.upper()
    return _KNOWN.get(h, {}).get("light2") or _hls_shift(h, lambda l: l + (1 - l) * 0.47)


def nearest_gnome(h):
    r, g, b = _rgb(h)
    return min(GNOME_ACCENTS, key=lambda n: sum((a - c) ** 2 for a, c in zip((r, g, b), _rgb(GNOME_ACCENTS[n]))))


def current() -> str:
    if util.DEMO:
        return DEFAULT_ACCENT
    try:
        with open(CONFIG) as f:
            h = json.load(f).get("accent", "")
        if isinstance(h, str) and len(h) == 7 and h.startswith("#"):
            int(h[1:], 16)
            return h.upper()
    except (OSError, ValueError, AttributeError):
        pass
    # No exact colour stored yet: follow GNOME's named accent.
    name = util.gget("org.gnome.desktop.interface", "accent-color", "blue")
    return {"blue": DEFAULT_ACCENT, "teal": "#038387", "green": "#107C10", "yellow": "#FFB900",
            "orange": "#F7630C", "red": "#E81123", "pink": "#E3008C", "purple": "#744DA9",
            "slate": "#515C6B"}.get(name, DEFAULT_ACCENT)


