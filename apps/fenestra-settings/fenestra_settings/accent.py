def apply(h) -> bool:
    """Store and apply an accent colour. Returns False in read-only mode."""
    h = h.upper()
    if util.READ_ONLY:
        util.log("read-only: accent", h)
        return False
    os.makedirs(os.path.dirname(CONFIG), exist_ok=True)
    with open(CONFIG + ".tmp", "w") as f:
        json.dump({"accent": h}, f)
    os.replace(CONFIG + ".tmp", CONFIG)
    with open(SHELL_CSS + ".tmp", "w") as f:
        f.write(shell_css(h))
    os.replace(SHELL_CSS + ".tmp", SHELL_CSS)
    if util.have("dconf"):
        dots = light2(h)
        for i in range(1, 5):
            util.run_async(["dconf", "write", f"/org/gnome/shell/extensions/dash-to-panel/dot-color-{i}",
                            f"'{dots.lower()}'"], mutating=True)
    # Libadwaita apps get the nearest named accent; this also notifies theme.py.
    util.gset("org.gnome.desktop.interface", "accent-color", nearest_gnome(h))
    return True


def set_solid_background(h) -> bool:
    bg = "org.gnome.desktop.background"
    ok = util.gset(bg, "primary-color", h.lower())
    util.gset(bg, "color-shading-type", "solid")
    util.gset(bg, "picture-options", "none")
    return ok
