#!/usr/bin/bash
# Keep the laptop's local services working across Python and GDM upgrades.
#
#   sudo bash fix-local-services.sh --dry-run    show what would change, change nothing
#   sudo bash fix-local-services.sh              apply (backup first), then check
#   sudo bash fix-local-services.sh --rollback   restore the files from the last backup
#
# 1. Python paths. Local helpers (howdy-preload, galaxy-book-guard) had python3.14 written into
#    them; Fedora 45 has Python 3.15, so they failed (ModuleNotFoundError paths_factory). Here:
#    "python3.N" commands become "python3", and .../pythonN.M/site-packages paths are moved to
#    the running Python's version. Run again after every Python upgrade (the Fenestra release
#    upgrade does it in its post-boot step).
# 2. Face sign-in on the login screen. Fedora 45 ships GDM's PAM stack in /usr/lib/pam.d and
#    left the old /etc/pam.d/gdm-password as .rpmsave, so Howdy was no longer asked. Here
#    /etc/pam.d/gdm-password is regenerated from the vendor file with Howdy's line(s) (taken
#    from the old file) before the password stack (gdm-password-auth-substack on Fedora 45). gdm-password is not an authselect-managed
#    file, so authselect keeps working; the generated file is marked and regenerated whenever
#    the vendor file changes, so GDM updates are picked up.
# Never restarts GDM or the computer.
set -euo pipefail
BACKUPS=/var/backups/fenestra-local-services
LOG=/var/log/fenestra-local-services.log
MARK='# Generated by Fenestra (fix-local-services.sh) from /usr/lib/pam.d/gdm-password'
DRY=0
say() { echo "$*"; [ $DRY = 1 ] || echo "$(date -Is) $*" >> "$LOG"; }
[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }

PYVER=$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')
# Files written for this laptop that may embed a Python version.
CANDIDATES=(/usr/local/lib/howdy-preload /usr/local/lib/galaxy-book-guard
            /etc/systemd/system/howdy-preload.service /etc/systemd/system/galaxy-book-check.service
            /usr/local/bin/howdy-preload)

files_to_fix() {
    for c in "${CANDIDATES[@]}"; do
        [ -e "$c" ] || continue
        find "$c" -type f -size -2M 2>/dev/null
    done | while IFS= read -r f; do
        grep -Iq . "$f" 2>/dev/null || continue          # text files only
        grep -Eq "python3\.[0-9]+" "$f" && echo "$f"
    done
}

fix_python_paths() {  # $1 file -> rewritten copy on stdout
    python3 - "$1" "$PYVER" <<'PY'
import re, sys
path, ver = sys.argv[1], sys.argv[2]
s = open(path).read()
# site-packages / lib dirs: the running version (re-run after the next upgrade)
s = re.sub(r'(/usr/(?:local/)?lib(?:64)?/python)3\.\d+(?=/)', lambda m: m.group(1) + ver, s)
# interpreters: version-free
s = re.sub(r'(?<![\w./-])((?:/usr(?:/local)?)?/bin/)?python3\.\d+(?![\w.])', lambda m: (m.group(1) or '') + 'python3', s)
sys.stdout.write(s)
PY
}

howdy_lines() {
    local old=/etc/pam.d/gdm-password.rpmsave
    if [ -f "$old" ] && grep -q pam_howdy "$old"; then grep pam_howdy "$old"
    else echo 'auth        sufficient    pam_howdy.so'; fi
}

gen_pam() {  # -> generated /etc/pam.d/gdm-password on stdout
    local vendor=/usr/lib/pam.d/gdm-password
    python3 - "$vendor" "$MARK" "$(sha256sum "$vendor" | cut -d' ' -f1)" "$(howdy_lines)" <<'PY'
import re, sys
vendor, mark, digest, howdy = sys.argv[1:5]
out, done = [f'{mark}\n', f'# vendor-sha256 {digest}\n'], False
for line in open(vendor):
    # Before the password stack: password-auth / system-auth (Fedora <= 44) or
    # gdm-password-auth-substack (Fedora 45, GDM 51); never before postlogin.
    if not done and re.match(r'\s*-?auth\s+(substack|include)\s+(?!postlogin)\S+', line):
        out += [h + '\n' for h in howdy.splitlines() if h.strip()]
        done = True
    out.append(line)
if not done:
    sys.exit('no auth substack/include line in the vendor file')
sys.stdout.write(''.join(out))
PY
}

pam_needed() {
    [ -f /usr/lib/pam.d/gdm-password ] || return 1                  # older layout: nothing to do
    [ -f /usr/lib64/security/pam_howdy.so ] || [ -f /usr/lib/security/pam_howdy.so ] || return 1
    local cur=/etc/pam.d/gdm-password
    if [ -f "$cur" ] && ! grep -qF "$MARK" "$cur"; then
        say "note: $cur exists and was not generated by Fenestra; left as it is"
        return 1
    fi
    [ -f "$cur" ] && grep -q "vendor-sha256 $(sha256sum /usr/lib/pam.d/gdm-password | cut -d' ' -f1)" "$cur" && return 1
    return 0
}

apply() {
    local b="$BACKUPS/$(date +%Y%m%d-%H%M%S)" changed=0
    [ $DRY = 1 ] || install -d -m 0700 "$b"
    while IFS= read -r f; do
        local new; new=$(mktemp)
        fix_python_paths "$f" > "$new"
        if ! cmp -s "$f" "$new"; then
            say "python paths: $f"
            diff -u "$f" "$new" | sed -n '3,200p' || true
            if [ $DRY = 0 ]; then
                install -D -m 0600 "$f" "$b/files$f"
                cat "$new" > "$f"                                   # keeps owner, mode, SELinux label
                changed=1
            fi
        fi
        rm -f "$new"
    done < <(files_to_fix)

    if pam_needed; then
        local new; new=$(mktemp)
        gen_pam > "$new"
        say "PAM: /etc/pam.d/gdm-password (Howdy before the password stack)"
        diff -u /usr/lib/pam.d/gdm-password "$new" | sed -n '3,80p' || true
        if [ $DRY = 0 ]; then
            [ -f /etc/pam.d/gdm-password ] && install -D -m 0600 /etc/pam.d/gdm-password "$b/files/etc/pam.d/gdm-password"
            echo /etc/pam.d/gdm-password >> "$b/created.txt"
            install -m 0644 "$new" /etc/pam.d/gdm-password
            restorecon /etc/pam.d/gdm-password 2>/dev/null || true
            changed=1
        fi
        rm -f "$new"
    fi
    [ $DRY = 1 ] && { echo "(dry run: nothing changed)"; return 0; }
    if [ $changed = 1 ]; then
        systemctl daemon-reload 2>/dev/null || true
        for u in howdy-preload.service galaxy-book-check.service; do
            systemctl cat "$u" >/dev/null 2>&1 && systemctl restart "$u" 2>/dev/null || true
        done
        say "backup: $b"
    else
        rmdir "$b" 2>/dev/null || true
        say "nothing to change"
    fi
    check
}

check() {
    local howdy_dir
    howdy_dir=$(python3 -c 'import sysconfig, os; p=os.path.join(sysconfig.get_paths()["purelib"], "howdy"); print(p if os.path.isdir(p) else "")')
    if [ -n "$howdy_dir" ]; then
        if (cd "$howdy_dir" && python3 -c 'import paths_factory' 2>/dev/null); then say "ok: Howdy modules import with Python $PYVER"
        else say "PROBLEM: Howdy modules do not import with Python $PYVER ($howdy_dir)"; fi
    fi
    for u in howdy-preload.service galaxy-book-check.service; do
        systemctl cat "$u" >/dev/null 2>&1 || continue
        if systemctl is-failed -q "$u"; then say "PROBLEM: $u failed: journalctl -u $u -b"
        else say "ok: $u $(systemctl is-active "$u")"; fi
    done
    if [ -f /usr/lib/pam.d/gdm-password ]; then
        grep -qs pam_howdy /etc/pam.d/gdm-password && say "ok: Howdy in the GDM login (gdm-password)" \
            || say "note: Howdy is not in the GDM login"
    fi
}

rollback() {
    local b; b=$(ls -1d "$BACKUPS"/*/ 2>/dev/null | tail -1 || true)
    [ -n "$b" ] || { echo "no backup in $BACKUPS"; exit 1; }
    b=${b%/}
    if [ -d "$b/files" ]; then
        (cd "$b/files" && find . -type f) | while IFS= read -r f; do
            cat "$b/files/${f#./}" > "/${f#./}"; say "restored /${f#./}"
        done
    fi
    if [ -f "$b/created.txt" ]; then
        while IFS= read -r f; do
            [ -f "$b/files$f" ] || { rm -f "$f"; say "removed $f (not there before)"; }
        done < "$b/created.txt"
    fi
    systemctl daemon-reload 2>/dev/null || true
    say "rolled back to $b"
}

case "${1:-}" in
    --dry-run) DRY=1; apply ;;
    "") apply ;;
    --rollback) rollback ;;
    --check) check ;;
    *) sed -n 2,19p "$0"; exit 1 ;;
esac
